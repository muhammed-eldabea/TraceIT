'use strict';
const assert = require('node:assert/strict');
const { parseManualLinks } = require('../src/manualLinks');
const { analyze } = require('../src/engine');
const config = {sources:[{name:'req',include:'r',artifact:'^(?<id>R[0-9]+)'},{name:'test',include:'t',artifact:'^(?<id>T[0-9]+)'}],links:[{from:'test',to:'req',type:'verifies'}]};
const manual = {from:{source:'test',id:'T1'},to:{source:'req',id:'R1'},type:'verifies'};
const files=[{source:'req',path:'r',text:'R1\nR2'},{source:'test',path:'t',text:'T1'}];
const data=parseManualLinks(JSON.stringify({version:1,links:[manual]}));
const result=analyze({...config,manualLinks:data.links},files);
assert.equal(result.links.length,1); assert.equal(result.links[0].manual,true); assert.equal(result.coverage[0].covered,1);
const missing=analyze({...config,manualLinks:[{...manual,to:{source:'req',id:'R9'}}]},files);
assert.equal(missing.links.length,0); assert.match(missing.diagnostics[0],/missing or ambiguous/);
const ambiguous=analyze({...config,manualLinks:[manual]},[...files,{source:'req',path:'other',text:'R1'}]);
assert.equal(ambiguous.links.length,0);
assert.throws(()=>parseManualLinks(JSON.stringify({version:1,links:[manual,manual]})),/Duplicate/);
assert.throws(()=>parseManualLinks('{'),/Invalid/);
console.log('Manual link tests passed');
const {replaceManualLink} = require('../src/manualLinks');
const second = {...manual,to:{source:'req',id:'R2'}};
assert.deepEqual(replaceManualLink([manual],0,second),[second]);
assert.throws(()=>replaceManualLink([manual,second],0,second),/Duplicate/);
assert.throws(()=>replaceManualLink([manual],2,second),/no longer exists/);
