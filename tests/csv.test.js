'use strict';
const assert = require('node:assert/strict');
const {parseCsv}=require('../src/csv');
const {analyze}=require('../src/engine');
const source={name:'doors-export',format:'csv',include:'*.csv',idColumn:'ID',titleColumn:'Title',textColumn:'Text',referenceColumn:'Links'};
const text='ID,Title,Text,Links\r\nR1,"Login, secure","First line\nsecond line","P1; P2"\r\nR2,Logout,Done,\r\n';
const result=parseCsv(text,source,'doors.csv');
assert.equal(result.artifacts.length,2);
assert.equal(result.artifacts[0].title,'Login, secure');
assert.equal(result.artifacts[0].text,'First line\nsecond line');
assert.equal(result.artifacts[0].line,2); assert.equal(result.artifacts[1].line,4);
assert.deepEqual(result.artifacts[0].references.map(r=>r.target),['P1','P2']);
assert.throws(()=>parseCsv('Wrong,Title\n1,A',source,'x'),/column not found/);
assert.throws(()=>parseCsv('ID,ID,Title,Text,Links\n1,2,a,b,c',source,'x'),/unique/);
const cfg={sources:[source,{name:'parent',format:'csv',include:'p.csv',idColumn:'ID'}],links:[{from:'doors-export',to:'parent',type:'satisfies'}]};
const analyzed=analyze(cfg,[{source:'doors-export',path:'doors.csv',text},{source:'parent',path:'p.csv',text:'ID\nP1\nP2\n'}]);
assert.equal(analyzed.links.length,2); assert.equal(analyzed.coverage[0].covered,2);
console.log('CSV parser tests passed');
assert.throws(()=>parseCsv('',source,'empty.csv'),/no header/);
const attributedSource={name:'req',format:'csv',idColumn:'ID',attributeColumns:['Status','Owner']};
const attributed=parseCsv('ID,Status,Owner\nR1,Approved,"Smith, Jane"\n',attributedSource,'requirements.csv');
assert.deepEqual(attributed.artifacts[0].attributes,{Status:'Approved',Owner:'Smith, Jane'});
assert.throws(()=>parseCsv('ID,Status\nR1,Draft\n',attributedSource,'x.csv'),/column not found: Owner/);
assert.throws(()=>parseCsv('ID\nR1\n',{...attributedSource,attributeColumns:'Status'},'x.csv'),/attributeColumns/);
assert.throws(()=>parseCsv('ID,Status\nR1,Draft\n',{...attributedSource,attributeColumns:['Status','Status']},'x.csv'),/attributeColumns/);
const richResult=analyze({sources:[{...attributedSource,include:'requirements.csv'}]},[{source:'req',path:'requirements.csv',text:'ID,Status,Owner\nR1,Approved,Jane\n'}]);
assert.match(require('../src/engine').report(richResult),/Approved/);
const baseline=require('../src/baseline');
const changedResult=analyze({sources:[{...attributedSource,include:'requirements.csv'}]},[{source:'req',path:'requirements.csv',text:'ID,Status,Owner\nR1,Draft,Jane\n'}]);
assert.equal(baseline.compare(baseline.snapshot(richResult,'p'),baseline.snapshot(changedResult,'p')).changed.length,1);
