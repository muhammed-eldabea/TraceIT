'use strict';
const JSZip=require('jszip');
const ExcelJS=require('exceljs');
const {XMLParser,XMLValidator}=require('fast-xml-parser');
const path=require('path').posix;
const local=(obj,name)=>obj && Object.entries(obj).find(([key])=>key.split(':').pop()===name)?.[1];
const list=value=>value==null?[]:Array.isArray(value)?value:[value];
const xmlEscape=value=>value.replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;').replace(/\r/g,'&#13;');
async function editTextCell(bytes,{sheet,address,value}) {
  if(typeof sheet!=='string' || !sheet || typeof address!=='string' || !/^[A-Za-z]{1,3}[1-9][0-9]{0,6}$/.test(address))throw new Error('Enter a worksheet name and a valid cell address');
  if(typeof value!=='string' || value.length>32767 || /[\x00-\x08\x0b\x0c\x0e-\x1f\ufffe\uffff]|[\uD800-\uDBFF](?![\uDC00-\uDFFF])|(?<![\uD800-\uDBFF])[\uDC00-\uDFFF]/.test(value))throw new Error('Text contains unsupported characters or exceeds Excel’s 32,767-character limit');
  const original=Buffer.from(bytes), zip=await JSZip.loadAsync(original);
  if(Object.keys(zip.files).some(name=>/^_xmlsignatures\//i.test(name) || /^xl\/vbaProject\.bin$/i.test(name)))throw new Error('Signed or macro-enabled workbooks are not supported');
  const workbook=new ExcelJS.Workbook();await workbook.xlsx.load(original);
  const worksheet=workbook.getWorksheet(sheet);if(!worksheet)throw new Error(`Worksheet not found: ${sheet}`);
  if(worksheet.sheetProtection)throw new Error('Protected worksheets cannot be edited');
  const normalized=address.toUpperCase();const cell=worksheet.getCell(normalized);
  if(cell.isMerged)throw new Error('Merged cells cannot be edited');
  if(typeof cell.value!=='string')throw new Error('Only existing plain-text cells can be edited; formulas, numbers, rich text, hyperlinks and empty cells are not supported');
  const read=async name=>{const entry=zip.file(name);if(!entry)throw new Error(`Workbook is missing ${name}`);return entry.async('string');};
  const workbookXml=await read('xl/workbook.xml');
  if(/<(?:[\w.-]+:)?workbookProtection\b/i.test(workbookXml))throw new Error('Protected workbooks cannot be edited');
  const relationshipsXml=await read('xl/_rels/workbook.xml.rels');
  for(const xml of [workbookXml,relationshipsXml])if(XMLValidator.validate(xml)!==true)throw new Error('Workbook XML is invalid');
  const parser=new XMLParser({ignoreAttributes:false,processEntities:true});
  const root=local(parser.parse(workbookXml),'workbook'), sheetRoot=local(root,'sheets');
  const sheets=list(local(sheetRoot,'sheet'));
  const selected=sheets.find(item=>item['@_name']===sheet);
  const relationId=selected && Object.entries(selected).find(([key])=>key.startsWith('@_') && key.split(':').pop()==='id')?.[1];
  const relRoot=local(parser.parse(relationshipsXml),'Relationships');
  const relationship=list(local(relRoot,'Relationship')).find(item=>item['@_Id']===relationId);
  if(!relationship || relationship['@_TargetMode']==='External' || !String(relationship['@_Type']||'').endsWith('/worksheet'))throw new Error('Could not resolve worksheet file safely');
  const target=String(relationship['@_Target']||'');
  const worksheetPath=target.startsWith('/') ? path.normalize(target.slice(1)) : path.normalize(path.join('xl',target));
  if(!/^xl\/worksheets\/[^/]+\.xml$/.test(worksheetPath))throw new Error('Unsupported worksheet file location');
  const xml=await read(worksheetPath);
  if(XMLValidator.validate(xml)!==true)throw new Error('Worksheet XML is invalid');
  if(/<(?:[\w.-]+:)?sheetProtection\b/i.test(xml))throw new Error('Protected worksheets cannot be edited');
  const elements=[...xml.matchAll(/<([\w.-]+:)?c(?=\s|\/?>)[^>]*?(?:\/>|>[\s\S]*?<\/\1?c\s*>)/g)];
  const matching=elements.filter(m=>{const tag=m[0].match(/^<[^>]+>/)?.[0] || '';const match=tag.match(/(?:^|\s)r\s*=\s*(["'])([^"']+)\1/);return match && match[2].toUpperCase()===normalized;});
  if(matching.length!==1)throw new Error('Could not locate a unique existing worksheet cell');
  const match=matching[0], old=match[0], opening=old.match(/^<([\w.-]+:)?c\b([^>]*?)(\/?)>/);
  if(!opening || /(?:^|\s)(?:cm|vm)\s*=/.test(opening[2]) || /<(?:[\w.-]+:)?(?:f|extLst)\b/.test(old))throw new Error('This cell has unsupported formula or metadata');
  const prefix=opening[1]||'', attrs=opening[2].replace(/\s+t\s*=\s*(["'])[^"']*\1/g,'');
  const replacement=`<${prefix}c${attrs} t="inlineStr"><${prefix}is><${prefix}t xml:space="preserve">${xmlEscape(value)}</${prefix}t></${prefix}is></${prefix}c>`;
  const updated=xml.slice(0,match.index)+replacement+xml.slice(match.index+old.length);
  if(XMLValidator.validate(updated)!==true)throw new Error('Edited worksheet XML did not validate');
  zip.file(worksheetPath,updated);
  const output=await zip.generateAsync({type:'nodebuffer',compression:'DEFLATE'});
  const verify=new ExcelJS.Workbook();await verify.xlsx.load(output);
  if(verify.getWorksheet(sheet)?.getCell(normalized).value!==value)throw new Error('Edited workbook verification failed');
  return output;
}
module.exports={editTextCell};
